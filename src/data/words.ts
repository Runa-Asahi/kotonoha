import type { DeckId, Word } from "@/data/types";

type Draft = {
  word: string;
  reading: string;
  ipa?: string;
  pos: string;
  meaning: string;
  parts: { t: string; g: string }[];
  hook: string;
  example: string;
  exampleZh: string;
  roma?: string;
};

function pack(deck: DeckId, list: Draft[]): Word[] {
  return list.map((item) => ({
    id: `${deck}-${item.word}`,
    deck,
    ...item,
  }));
}

